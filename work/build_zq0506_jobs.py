def build(slug, scenes, pal, out_prefix, seed0):
    base = ("厚涂绘本风格的中国历史场景插画,干净利落的轮廓线,统一暖羊皮纸色调并以" + pal +
            "点缀,全景式电影构图铺满画面,环境有纵深与氛围,背景整洁连贯,人物结构准确,"
            "无多余肢体,无扭曲面孔。")
    jobs = []
    for ch, arr in scenes.items():
        for bi, sc in enumerate(arr):
            jobs.append({"out": f"work/broll/{slug}/{ch}_{bi}.png",
                         "seed": seed0 + len(jobs), "size": "1536x864",
                         "preset": "qwen21" if bi == 0 else "qwen21-turbo",
                         "prompt": base + sc + "。" + TAIL})
        jobs.append({"out": f"work/broll/{slug}/{ch}_bg.png",
                     "seed": seed0 + 50 + len(jobs), "size": "1536x864",
                     "preset": "qwen21-turbo", "prompt": BG})
    json.dump(jobs, open(f"work/{out_prefix}_images.json", "w", encoding="utf-8"),
              ensure_ascii=False, indent=1)
    return len(jobs)


def wire(slug):
    c = json.load(open(f"src/mzx_story/{slug}.json", encoding="utf-8"))
    BG = ("Warm light beige handmade paper background, extremely subtle bamboo slip "
          "strip texture fading in from the left and right edges, flat, minimal, "
          "clean empty center area, ancient Chinese parchment mood, no objects, "
          "no text, no letters, no watermark.")
    for ch in c["chapters"]:
        ch["bg"] = BG
        n = 2 if ch["kind"] == "s9" else 4
        step = 1.0 / n
        ch["broll"] = [{"prompt": "scene", "at": round(i * step, 3),
                        "hold": round(step + 0.015, 3), "fit": "contain"} for i in range(n)]
        for s in re.split(r"[。!?;]", ch["narration"]):
            if s.strip() and len(s.strip()) > 44:
                raise SystemExit(f"超长: {slug} {ch['kind']} {s}")
    json.dump(c, open(f"src/mzx_story/{slug}.json", "w", encoding="utf-8"),
              ensure_ascii=False, indent=2)


